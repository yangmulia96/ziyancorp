export const detectLanguage = () => {
  if (typeof window === 'undefined') return 'en';
  try {
    const saved = localStorage.getItem('ziyan-lang');
    if (saved && translations[saved]) return saved;

    const navLangs = navigator.languages || [navigator.language || navigator.userLanguage || ''];
    for (const lang of navLangs) {
      if (!lang) continue;
      const code = lang.toLowerCase().split('-')[0];
      if (translations[code]) return code;
    }
  } catch (e) {
    // fallback
  }
  return 'en';
};

export const I18nContext = createContext(null);

export const I18nProvider = ({ children, initialLanguage }) => {
  const [language, setLanguageState] = useState(() => initialLanguage || detectLanguage());

  const setLanguage = useCallback((lang) => {
    if (translations[lang]) {
      setLanguageState(lang);
      try {
        localStorage.setItem('ziyan-lang', lang);
        if (typeof document !== 'undefined') {
          document.documentElement.lang = lang;
          document.documentElement.dir = SUPPORTED_LANGUAGES[lang]?.dir || 'ltr';
        }
      } catch (e) {
        // ignore
      }
    }
  }, []);

  useEffect(() => {
    try {
      if (typeof document !== 'undefined') {
        document.documentElement.lang = language;
        document.documentElement.dir = SUPPORTED_LANGUAGES[language]?.dir || 'ltr';
      }
    } catch (e) {
      // ignore
    }
  }, [language]);

  const t = useCallback((key, fallback) => {
    const langDict = translations[language] || translations.en;
    if (langDict && langDict[key] !== undefined) {
      return langDict[key];
    }
    if (translations.en && translations.en[key] !== undefined) {
      return translations.en[key];
    }
    return fallback !== undefined ? fallback : key;
  }, [language]);

  const value = useMemo(() => ({
    language,
    lang: language,
    setLanguage,
    setLang: setLanguage,
    t,
    dir: SUPPORTED_LANGUAGES[language]?.dir || 'ltr',
    isRtl: (SUPPORTED_LANGUAGES[language]?.dir || 'ltr') === 'rtl',
    supportedLanguages: Object.keys(translations),
    languages: SUPPORTED_LANGUAGES,
  }), [language, setLanguage, t]);

  return (
    <I18nContext.Provider value={value}>
      {children}
    </I18nContext.Provider>
  );
};

export const useTranslation = () => {
  const context = useContext(I18nContext);
  if (!context) {
    const fallbackLang = detectLanguage();
    const t = (key, fallback) => {
      const langDict = translations[fallbackLang] || translations.en;
      return langDict?.[key] ?? translations.en?.[key] ?? (fallback !== undefined ? fallback : key);
    };
    return {
      language: fallbackLang,
      lang: fallbackLang,
      setLanguage: () => {},
      setLang: () => {},
      t,
      dir: SUPPORTED_LANGUAGES[fallbackLang]?.dir || 'ltr',
      isRtl: SUPPORTED_LANGUAGES[fallbackLang]?.dir === 'rtl',
      supportedLanguages: Object.keys(translations),
      languages: SUPPORTED_LANGUAGES,
    };
  }
  return context;
};

export default I18nProvider;
